for (const lang of ['id','ja']) Object.assign(I18N[lang], I18N_EXTRA[lang]);

let CURRENT_LANG = (() => {
  try {
    const saved = localStorage.getItem('emenda_lang');
    return ['en','id','ja'].includes(saved) ? saved : 'en';
  } catch(e) { return 'en'; }
})();

const I18N_TEXT_SOURCE = new WeakMap();
const I18N_ATTR_SOURCE = new WeakMap();

function translateTextNode(node, lang){
  if(!I18N_TEXT_SOURCE.has(node)) I18N_TEXT_SOURCE.set(node,node.nodeValue);
  const source = I18N_TEXT_SOURCE.get(node);
  const trimmed = source.trim();
  if(!trimmed) return;
  const dict = I18N[lang] || {};
  const translated = dict[trimmed] || trimmed;
  const lead = source.match(/^\s*/)?.[0] || '';
  const trail = source.match(/\s*$/)?.[0] || '';
  node.nodeValue = lead + translated + trail;
}

function translateAttributes(el, lang){
  if(!I18N_ATTR_SOURCE.has(el)){
    I18N_ATTR_SOURCE.set(el,{
      placeholder: el.getAttribute('placeholder'),
      title: el.getAttribute('title'),
      ariaLabel: el.getAttribute('aria-label')
    });
  }
  const src = I18N_ATTR_SOURCE.get(el);
  const dict = I18N[lang] || {};
  if(src.placeholder !== null) el.setAttribute('placeholder',dict[src.placeholder] || src.placeholder);
  if(src.title !== null) el.setAttribute('title',dict[src.title] || src.title);
  if(src.ariaLabel !== null && src.ariaLabel !== 'Language') el.setAttribute('aria-label',dict[src.ariaLabel] || src.ariaLabel);
}

function applyLanguage(root=document.body){
  document.documentElement.lang = CURRENT_LANG === 'ja' ? 'ja' : (CURRENT_LANG === 'id' ? 'id' : 'en');
  const dict = I18N[CURRENT_LANG] || {};

  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  let n;
  while(n=walker.nextNode()){
    const p=n.parentElement;
    if(!p || ['SCRIPT','STYLE'].includes(p.tagName)) continue;

    if(n.__emendaOriginalText === undefined) n.__emendaOriginalText=n.nodeValue;
    const source=n.__emendaOriginalText;
    const trimmed=source.trim();
    if(!trimmed) continue;

    const lead=(source.match(/^\s*/)||[''])[0];
    const trail=(source.match(/\s*$/)||[''])[0];
    const translated=CURRENT_LANG==='en' ? trimmed : (dict[trimmed] || trimmed);
    n.nodeValue=lead+translated+trail;
  }

  root.querySelectorAll('input,textarea,button,a,select,option').forEach(el=>{
    if(!el.__emendaOriginalAttrs){
      el.__emendaOriginalAttrs={
        placeholder:el.getAttribute('placeholder'),
        title:el.getAttribute('title'),
        ariaLabel:el.getAttribute('aria-label')
      };
    }
    const src=el.__emendaOriginalAttrs;
    if(src.placeholder!==null) el.setAttribute('placeholder',CURRENT_LANG==='en'?src.placeholder:(dict[src.placeholder]||src.placeholder));
    if(src.title!==null) el.setAttribute('title',CURRENT_LANG==='en'?src.title:(dict[src.title]||src.title));
    if(src.ariaLabel!==null && src.ariaLabel!=='Language') el.setAttribute('aria-label',CURRENT_LANG==='en'?src.ariaLabel:(dict[src.ariaLabel]||src.ariaLabel));
  });

  document.querySelectorAll('.lang-btn').forEach(btn=>{
    const active=btn.dataset.lang===CURRENT_LANG;
    btn.classList.toggle('active',active);
    btn.setAttribute('aria-pressed',active?'true':'false');
  });
}

function setLanguage(lang){
  if(!['en','id','ja'].includes(lang)) return;
  CURRENT_LANG=lang;
  try{ localStorage.setItem('emenda_lang',lang); }catch(e){}
  render();
  closeMobile();
}

document.addEventListener('click',e=>{
  const b=e.target.closest('.lang-btn');
  if(!b) return;
  e.preventDefault();
  e.stopPropagation();
  setLanguage(b.dataset.lang);
});
